// 按难度分组
const DIFF_MAP = {
  easy: { label: '简单', min: 1, max: 20 },
  medium: { label: '中阶', min: 21, max: 50 },
  hard: { label: '高阶', min: 51, max: 99 }
};

function getDifficulty(levelId) {
  const id = parseInt(levelId);
  if (id <= 20) return 'easy';
  if (id <= 50) return 'medium';
  return 'hard';
}

// 解析坐标 → block对象（0-indexed）
function parseLevel(level) {
  const blocks = [];
  const tc = level.target.map(([r,c]) => [r-1, c-1]);
  blocks.push({
    id: 'G', type: 'target', orient: tc[1][0] > tc[0][0] ? 'v' : 'h',
    size: tc.length, row: tc[0][0], col: tc[0][1]
  });
  // 障碍物（跳过 G 避免冲突）
  let oi = 0;
  level.blocks.forEach((coords) => {
    const cells = coords.map(([r,c]) => [r-1, c-1]);
    const dr = cells[cells.length-1][0] - cells[0][0];
    // 确保 id 不是 'G'
    let id;
    do {
      id = String.fromCharCode(65 + oi);
      oi++;
    } while (id === 'G');
    blocks.push({
      id: id,
      type: 'obstacle', orient: dr > 0 ? 'v' : 'h',
      size: cells.length, row: cells[0][0], col: cells[0][1]
    });
  });
  return blocks;
}

function buildGroups() {
  const groups = { easy: [], medium: [], hard: [] };
  for (const lev of LEVELS) {
    const diff = getDifficulty(lev.id);
    groups[diff].push(lev);
  }
  return groups;
}

const LEVEL_GROUPS = buildGroups();
const ALL_LEVELS = LEVELS;

module.exports = { LEVELS, LEVEL_GROUPS, ALL_LEVELS, DIFF_MAP, parseLevel, getDifficulty };
